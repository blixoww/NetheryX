def frame(rows, colors):
    img = new(8)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in colors:
                img.putpixel((x, y), hexc(colors[ch][0], colors[ch][1]) if isinstance(colors[ch], tuple) else hexc(colors[ch]))
    return img


